#!/usr/bin/env python3
"""Pin and stage the separately released electronics module; never execute lock contents."""
import hashlib
import io
from pathlib import Path
import re
import subprocess
import sys
import tarfile
import tomllib
import zipfile

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / 'packaging/electronics.lock'


def download(url):
    return subprocess.check_output(['curl', '-fLsS', '--retry', '3', url])


def main():
    lock = tomllib.loads(LOCK.read_text())
    command = sys.argv[1]
    if command == 'update':
        version = sys.argv[2]
        if not re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+', version):
            raise ValueError('Use a three-part release version, for example 0.1.0')
        text = f'# Generated by scripts/update-electronics-lock.sh; review before merge.\nversion = "{version}"\n'
        for target in lock['targets']:
            asset = f'dutchman-electronics-{version}-{target}' + ('.zip' if 'windows' in target else '.tar.gz')
            url = f'https://github.com/dutchman-cad/dutchman-electronics/releases/download/v{version}/{asset}'
            checksum = download(url + '.sha256').decode().split()[0]
            if not re.fullmatch('[0-9a-fA-F]{64}', checksum):
                raise ValueError(f'No SHA-256 in {asset}.sha256; ask the module maintainers to publish it')
            text += f'\n[targets.{target}]\nasset = "{asset}"\nurl = "{url}"\nsha256 = "{checksum.lower()}"\n'
        LOCK.write_text(text)
        return
    target, dest = sys.argv[2:]
    entry = lock['targets'][target]
    checksum = entry['sha256']
    if not re.fullmatch('[0-9a-f]{64}', checksum):
        raise ValueError('Electronics checksum is missing; run scripts/update-electronics-lock.sh before packaging')
    data = download(entry['url'])
    if hashlib.sha256(data).hexdigest() != checksum:
        raise ValueError('Electronics download SHA-256 differs from the lock; check the release before retrying')
    # Read regular files only, never extract paths or links from the archive.
    files = {}
    if entry['asset'].endswith('.zip'):
        with zipfile.ZipFile(io.BytesIO(data)) as archive:
            for member in archive.infolist():
                if not member.is_dir():
                    files[member.filename] = archive.read(member)
    else:
        with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as archive:
            for member in archive:
                if member.isfile():
                    files[member.name] = archive.extractfile(member).read()
    program = 'dutchman-electronics' + ('.exe' if 'windows' in target else '')
    binaries = [name for name in files if Path(name).name == program]
    notices = [name for name in files if Path(name).name.upper().startswith(('LICENSE', 'LICENCE', 'COPYING', 'NOTICE'))]
    if len(binaries) != 1 or not notices:
        raise ValueError('Module archive must contain one program and license/notice files; ask the module maintainers to include them')
    dest = Path(dest)
    dest.mkdir(parents=True, exist_ok=True)
    (dest / program).write_bytes(files[binaries[0]])
    (dest / program).chmod(0o755)
    for name in notices:
        relative = Path(name)
        if relative.is_absolute() or '..' in relative.parts:
            raise ValueError('Module notice path is not supported; ask the module maintainers to repackage it')
        out = dest / 'THIRD-PARTY/dutchman-electronics' / relative
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(files[name])


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as error:
        sys.exit(str(error))
